const DICTS: Record<Lang, Record<TKey, string>> = { en, ru, uk }

export type TFunction = (key: TKey, vars?: Record<string, string | number>) => string

export const translate: TFunction = (key, vars) => {
  // default impl uses english; the context overrides with current lang
  return format(en[key], vars)
}

function format(template: string, vars?: Record<string, string | number>) {
  if (!vars) return template
  return template.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? `{${k}}`))
}

export function makeT(lang: Lang): TFunction {
  const dict = DICTS[lang] ?? en
  return (key, vars) => format(dict[key] ?? en[key] ?? key, vars)
}

type I18n = { lang: Lang; setLang: (lang: Lang) => void; t: TFunction }

export const I18nContext = createContext<I18n>({
  lang: 'en',
  setLang: () => {},
  t: translate,
})

export const useI18n = () => useContext(I18nContext)
